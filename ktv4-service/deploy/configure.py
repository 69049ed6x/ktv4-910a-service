"""Write portable shell configuration without changing inference code."""
import argparse
import os
from pathlib import Path
import shlex


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--model-path', required=True)
    parser.add_argument('--cann-env', required=True)
    parser.add_argument('--atb-env', required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    values = {
        'KTV4_MODEL_PATH': str(Path(args.model_path).expanduser().resolve()),
        'KTV4_CANN_ENV': str(Path(args.cann_env).expanduser().resolve()),
        'KTV4_ATB_ENV': str(Path(args.atb_env).expanduser().resolve()),
    }
    lines = ['# Generated by deploy/configure.py. Explicit environment variables take precedence.']
    for key, value in values.items():
        if '\n' in value or '\r' in value:
            raise ValueError('Paths must not contain newlines')
        lines.extend([f'if [[ -z "${{{key}:-}}" ]]; then',
                      f'  export {key}={shlex.quote(value)}', 'fi'])
    target = root / 'deployment.env'
    temporary = target.with_suffix('.tmp')
    temporary.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    os.chmod(temporary, 0o600)
    temporary.replace(target)
    print('Configuration saved:', target)


if __name__ == '__main__':
    main()
